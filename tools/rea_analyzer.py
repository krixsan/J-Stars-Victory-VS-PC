#!/usr/bin/env python3
"""
tools/rea_analyzer.py - REA Static Binary Analyzer & Auto-Stub Generator
Analyzes J-Stars Victory VS+ imported symbols/NIDs from out/link.json and out/import_names.txt,
matches with existing implementations in src/runtime_*.c, and auto-generates
safe SYSV_ABI stubs with diagnostic logging in src/runtime_jstars_stubs.c.
"""

import os
import sys
import json
import re
from pathlib import Path


def load_resolved_symbols(src_dir):
    """Scans all runtime_*.c and probe.c files for implemented function names and NIDs."""
    implemented = set()
    nids = set()

    for path in src_dir.glob("runtime*.c"):
        text = path.read_text(encoding="utf-8", errors="replace")
        # Match NID comparisons
        for m in re.finditer(r'runtime_nid_equals\(\s*\w+\s*,\s*"([^"]+)"\s*\)', text):
            nids.add(m.group(1))
        # Match symbol definitions with SYSV_ABI
        for m in re.finditer(r'SYSV_ABI\s+(?:[a-zA-Z0-9_*]+\s+)+([a-zA-Z0-9_]+)\s*\(', text):
            implemented.add(m.group(1))
        # Match table exports
        for m in re.finditer(r'\{\s*"([^"]+)"\s*,\s*(?:\([^)]+\))?\s*([a-zA-Z0-9_]+)\s*\}', text):
            nids.add(m.group(1))
            implemented.add(m.group(2))

    return implemented, nids


def main():
    workspace = Path(__file__).resolve().parent.parent
    src_dir = workspace / "src"
    out_dir = workspace / "out"

    import_names_file = out_dir / "import_names.txt"
    if not import_names_file.exists():
        print(f"[REA-Analyzer] {import_names_file} not found! Run tools/gen_import_names.py first.")
        sys.exit(1)

    print("[REA-Analyzer] Loading import names...")
    imports = []
    with open(import_names_file, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split(maxsplit=2)
            if len(parts) >= 3:
                nid, lib, sym = parts[0], parts[1], parts[2]
                imports.append((nid, lib, sym))

    print(f"[REA-Analyzer] Total imports in J-Stars: {len(imports)}")

    implemented_syms, implemented_nids = load_resolved_symbols(src_dir)
    print(f"[REA-Analyzer] Currently implemented functions/NIDs: {len(implemented_syms)} syms, {len(implemented_nids)} nids")

    # Categorize missing imports
    stubs_to_generate = []
    for nid, lib, sym in imports:
        qualified_nid = f"{nid}#{lib}"
        is_handled = False

        if qualified_nid in implemented_nids or nid in implemented_nids:
            is_handled = True
        elif sym != "?" and sym in implemented_syms:
            is_handled = True

        if not is_handled:
            stubs_to_generate.append((nid, lib, sym))

    print(f"[REA-Analyzer] Imports requiring stubs: {len(stubs_to_generate)}")

    # Generate src/runtime_jstars_stubs.h
    header_path = src_dir / "runtime_jstars_stubs.h"
    with open(header_path, "w", encoding="utf-8") as f:
        f.write("""/* Auto-generated by tools/rea_analyzer.py for J-Stars Victory VS+ (CUSA01593) */
#ifndef RUNTIME_JSTARS_STUBS_H
#define RUNTIME_JSTARS_STUBS_H

#include <stdint.h>
#include <stddef.h>

#ifdef __cplusplus
extern "C" {
#endif

uintptr_t runtime_jstars_resolve(const char *name);

#ifdef __cplusplus
}
#endif

#endif /* RUNTIME_JSTARS_STUBS_H */
""")
    print(f"[REA-Analyzer] Written header: {header_path}")

    # Generate src/runtime_jstars_stubs.c
    c_path = src_dir / "runtime_jstars_stubs.c"
    with open(c_path, "w", encoding="utf-8") as f:
        f.write("""/* Auto-generated by tools/rea_analyzer.py for J-Stars Victory VS+ (CUSA01593) */
#include "runtime_jstars_stubs.h"
#include "runtime.h"
#include <stdio.h>
#include <string.h>
#include <stdint.h>

#ifndef SYSV_ABI
#ifdef _WIN32
#define SYSV_ABI __attribute__((sysv_abi))
#else
#define SYSV_ABI
#endif
#endif

#define SCE_OK 0

/* --- REA Auto-Generated SYSV_ABI Stubs --- */
""")

        # Generate each stub function
        sanitized_funcs = {}
        for nid, lib, sym in stubs_to_generate:
            func_name = f"jstars_stub_{sym}" if sym != "?" else f"jstars_stub_nid_{nid.replace('-', '_').replace('+', '_')}"
            sanitized_funcs[(nid, lib)] = (func_name, sym)

        written_funcs = set()
        for (nid, lib), (func_name, sym) in sanitized_funcs.items():
            if func_name in written_funcs:
                continue
            written_funcs.add(func_name)

            f.write(f"""
static int64_t SYSV_ABI {func_name}(uint64_t a1, uint64_t a2, uint64_t a3, uint64_t a4, uint64_t a5, uint64_t a6) {{
    (void)a1; (void)a2; (void)a3; (void)a4; (void)a5; (void)a6;
    static int logged = 0;
    if (logged < 3) {{
        printf("[REA-STUB] Called %s (%s) from RIP: %p\\n", "{sym}", "{nid}", __builtin_return_address(0));
        logged++;
    }}
    return SCE_OK;
}}
""")

        # Generate resolver function
        f.write("""
uintptr_t runtime_jstars_resolve(const char *name) {
    if (!name) return 0;
""")

        for (nid, lib), (func_name, sym) in sanitized_funcs.items():
            pattern1 = f"{nid}#{lib}"
            f.write(f'    if (runtime_nid_equals(name, "{pattern1}")) return (uintptr_t){func_name};\n')
            f.write(f'    if (runtime_nid_equals(name, "{nid}")) return (uintptr_t){func_name};\n')
            if sym != "?":
                f.write(f'    if (!strcmp(name, "{sym}")) return (uintptr_t){func_name};\n')

        f.write("""    return 0;
}
""")

    print(f"[REA-Analyzer] Written stub file: {c_path} with {len(written_funcs)} functions.")


if __name__ == "__main__":
    main()
